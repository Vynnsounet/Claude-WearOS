    fun byId(id: String): Drug? = drugs.firstOrNull { it.id == id }

    /** Accent- and case-insensitive search over brand names, DCI and class, best matches first. */
    fun search(query: String): List<Drug> {
        val q = normalize(query)
        if (q.isBlank()) return drugs.sortedBy { normalize(it.dci) }
        val words = q.split(' ').filter { it.isNotBlank() }
        return drugs.mapNotNull { drug ->
            val names = normalize(drug.name)
            val dci = normalize(drug.dci)
            val haystack = "$names $dci ${normalize(drug.drugClass)} ${normalize(drug.indication)}"
            if (!words.all { it in haystack }) return@mapNotNull null
            val score = when {
                dci.startsWith(q) || names.split(", ").any { it.startsWith(q) } -> 0
                dci.contains(q) || names.contains(q) -> 1
                else -> 2
            }
            drug to score
        }.sortedWith(compareBy({ it.second }, { normalize(it.first.dci) })).map { it.first }
    }

    /** Allergies the user declared that match this drug, e.g. "Pénicilline" for amoxicillin. */
    fun allergyMatches(drug: Drug, allergies: List<String>): List<String> {
        val keys = (drug.allergyKeywords + drug.dci).map(::normalize)
        return allergies.filter { allergy ->
            val a = normalize(allergy)
            a.isNotBlank() && keys.any { k -> k.contains(a) || a.contains(k) }
        }
    }

    fun normalize(s: String): String =
        Normalizer.normalize(s.lowercase(), Normalizer.Form.NFD)
            .replace(Regex("\\p{Mn}+"), "")
            .replace("œ", "oe")
            .trim()
}
